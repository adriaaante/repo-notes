// АКТ сдачи-приёмки. Закрывает ВСЕ счета месяца (по строке на счёт); несданные разработки не включать.
// Формулировки короткие и универсальные — состав работ раскрывают договор и отчёт, а не акт.
const L = require('./lib.js');
const { CLIENT, p, h, AlignmentType } = L;
const CFG = {
  num: CLIENT.prefix + '00_', dateText: '«__» ________ 2026 г.',
  basis: CLIENT.contract,
  items: [{ name: 'Услуги по продвижению за ________ 2026 г.', price: '120 000,00' }],
  total: '120 000,00',
  totalWords: '120 000 (Сто двадцать тысяч) рублей 00 копеек',
  paidBy: 'Оплата произведена на основании счёта № ____ от __.__.2026 г.',
  out: 'Акт №' + CLIENT.prefix + '00_ ________ 2026 (120 000).docx',
};
L.save(CFG.out, [
  L.logo(),                                    // логотип FutureFlow — первым абзацем, справа (repo-notes, раздел 3.0)
  h(`АКТ № ${CFG.num}`), h('сдачи-приёмки оказанных услуг', 24), h(`от ${CFG.dateText}`, 22),
  p('Исполнитель: ' + L.ISP_LINE),
  p(`Заказчик: ${CLIENT.short}, ${CLIENT.inn_kpp}, ${CLIENT.address}, в лице ${CLIENT.director_title_genitive} ${CLIENT.director_genitive}.`),
  p('Основание: ' + CFG.basis, { after: 200 }),
  p('Исполнитель оказал, а Заказчик принял следующие услуги:', { after: 120 }),
  L.servicesTable(CFG.items),
  p(`Итого: ${CFG.total} руб. Без НДС.`, { align: AlignmentType.RIGHT, bold: true, after: 200 }),
  p(`Всего оказано услуг на сумму ${CFG.totalWords}. Без НДС.`),
  p(CFG.paidBy, { after: 200 }),
  p('Вышеперечисленные услуги оказаны полностью и в срок. Заказчик претензий по объёму, качеству и срокам оказания услуг не имеет.', { after: 200 }),
  p('Настоящий акт составлен в двух экземплярах, имеющих равную юридическую силу, по одному для каждой из Сторон.', { after: 400 }),
  L.signBlock(),
]);
